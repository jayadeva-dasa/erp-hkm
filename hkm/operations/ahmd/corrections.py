def remove_cancelled():
    count = 0
    for r in frappe.get_all(
        "Donation Receipt",
        filters={"old_dr_no": ["in", to_mark_ids], "docstatus": 1},
    ):
        print(r)
        count += 1
        frappe.db.set_value(
            "Donation Receipt",
            r["name"],
            {"docstatus": 2, "workflow_state": "Cancelled"},
        )

    print(count)
    frappe.db.commit()  # v16: OK - operations script


def set_commited_amount():
    for p in frappe.get_all("Patron", fields=["name", "seva_type"]):
        amount = frappe.db.get_value("Patron Seva Type", p["seva_type"], "seva_amount")
        frappe.db.set_value("Patron", p["name"], "committed_amount", amount)
    frappe.db.commit()  # v16: OK - operations script
